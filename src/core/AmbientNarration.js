let _lastAmbientStep = 0;
let _shownAmbient = new Set();
const AMBIENT_INTERVAL = 12; // 每12步可能触发一次
const AMBIENT_CHANCE = 0.25; // 25%触发概率

/**
 * 尝试获取一条环境叙事
 * @returns {string|null}
 */
export function tryAmbientNarration() {
  const steps = gameState.stats?.stepsWalked || 0;
  if (steps - _lastAmbientStep < AMBIENT_INTERVAL) return null;
  if (Math.random() > AMBIENT_CHANCE) return null;
  
  _lastAmbientStep = steps;
  
  const chapter = gameState.chapter || 1;
  const chapterLines = AMBIENT_LINES[chapter] || [];
  const universalLines = AMBIENT_LINES[0] || [];
  const all = [...chapterLines, ...universalLines];
  
  // Filter unseen
  const unseen = all.filter((_, i) => !_shownAmbient.has(chapter + '_' + i));
  if (unseen.length === 0) {
    _shownAmbient.clear();
    return all[Math.floor(Math.random() * all.length)];
  }
  
  const selected = unseen[Math.floor(Math.random() * unseen.length)];
  _shownAmbient.add(chapter + '_' + all.indexOf(selected));
  return selected;
}

/**
 * 渲染环境叙事（画面底部淡入淡出文字）
 */
export function renderAmbientText(ctx, canvasWidth, canvasHeight, text) {
  if (!text) return;
  
  ctx.save();
  ctx.font = '11px "Noto Serif SC", "Microsoft YaHei", serif';
  ctx.textAlign = 'center';
  ctx.fillStyle = 'rgba(120, 110, 90, 0.6)';
  
  // 带阴影的文字
  ctx.shadowColor = 'rgba(0, 0, 0, 0.5)';
  ctx.shadowBlur = 4;
  ctx.fillText(text, canvasWidth / 2, canvasHeight - 20);
  
  ctx.restore();
}
